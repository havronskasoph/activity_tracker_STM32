            "На плату все-таки пішов float32. Flash вистачало з великим запасом, а власна "
            "int8-реалізація вимагала б ручного переквантування між шарами — зайвий ризик "
            "помилки без практичної потреби. int8-версія підготовлена й перевірена; "
