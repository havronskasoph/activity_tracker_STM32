/* STM32WB BLE_AT_Server custom prediction service over UART4. */
#ifndef HAR_BLE_H
#define HAR_BLE_H
#include <stdint.h>

/* Set to 0 to use UART4 for another purpose. USB diagnostics remain enabled. */
#define HAR_BLE_ENABLED 1

/* Байтів у одному сповіщенні. Має бути <= char_value_len (20), заявленого
   в AT+BLE_CHAR_ADD, і <= 20 через типовий ATT MTU 23 без узгодження. */
#define HAR_BLE_CHUNK_SIZE 18u

/* Пауза між частинами довгого повідомлення. Сервер обробляє оновлення
   асинхронно, тому зовсім без паузи наступне може перетерти попереднє.
   Але пауза блокує головний цикл, а відліки акселерометра йдуть що 36 мс,
   тож тримаємо її мінімальною. */
#define HAR_BLE_CHUNK_GAP_MS 5u

/* Скільки сповіщень підряд має провалитися, перш ніж узяти паузу. Поки до
   пристрою ніхто не підключився, сервер на NOTIF_VAL відповідає ERROR — це
   нормальний стан, а не поломка, тому канал від цього не гасимо. */
#define HAR_BLE_FAIL_LIMIT 3u

/* Пауза після серії невдач. Без неї мовчазний модуль з'їдав би на таймаутах
   більше часу, ніж триває один крок вікна (~0.98 с), і інференс голодував би. */
#define HAR_BLE_BACKOFF_MS 5000u

/* Поновлення реклами.

   ЗАМІРЯНО НА ПЛАТІ: після того як клієнт підключився і відключився, сервер
   рекламу сам не відновлює — плата зникає з ефіру. Телефон побачив би її
   рівно один раз.

   Перша версія повторювала AT+BLE_ADV=1 кожні 20 с наосліп. Через 19 хвилин
   (близько 57 таких команд) модуль перестав відповідати взагалі — не ERROR,
   а тиша. Тому тепер рекламу поновлюємо лише один раз і лише тоді, коли
   сервер сам повідомив про відключення подією <BLE_EVT_CONN зі status 0. */
#define HAR_BLE_EVT_CONN  "BLE_EVT_CONN"

/* Скільки модуль має мовчати, перш ніж пробувати його оживити. */
/* Скидання підсистеми BLE командою AT+BLE_RST=1 на старті.

   НЕ ВМИКАТИ без потреби. Заміряно на платі: скидання справді повертає
   рекламу, коли модуль застряг у фантомному з'єднанні, АЛЕ після нього стек
   лишається недоготовим — перше ж підключення клієнта вбиває модуль намертво.
   У журналі це виглядає так: приходить подія <BLE_EVT_CONN=1, і з наступної
   команди модуль не каже жодного байта.

   Надійніший шлях — ловити подію про відключення й поновлювати рекламу, що
   стало можливим після переходу на приймання з перериваннями. */
#define HAR_BLE_RESET_ON_BOOT 0

#define HAR_BLE_REVIVE_MS 60000u

/* Скільки разів пробувати оживити, перш ніж здатися назовсім. Кожна спроба
   блокує головний цикл на кілька секунд, тому їх має бути небагато. */
#define HAR_BLE_REVIVE_TRIES 5u

/* Довжина нуля на WRLS_WKUP_B при спробі оживлення.

   Перевірено на платі: 50 мс (як при звичайному старті) і 1 с зависле модуля
   не витягують. Можливо, йому бракує часу розрядити власні конденсатори,
   тому тут помітно довше. Ця затримка блокує головний цикл, але трапляється
   не частіше разу на хвилину і лише тоді, коли BLE і так не працює. */
#define HAR_BLE_REVIVE_LOW_MS 5000u

/* Запасне поновлення реклами, якщо подію про відключення все-таки проґавили.
   Рідко навмисно: сліпе повторення кожні 20 с свого часу доконало модуль.
   Спрацьовує лише тоді, коли клієнт за нашими даними не підключений. */
#define HAR_BLE_READV_SAFETY_MS 300000u

/* 1 — друкувати в USB кожну AT-команду і відповідь модуля. Єдиний спосіб
   побачити, що саме відповідає BLE_AT_Server: UART4 заведений на модуль, з
   ноутбука до нього не дотягнутися. Друк відбувається після завершення
   команди, а не всередині прийому, щоб не губити байти відповіді. */
#define HAR_BLE_VERBOSE 1

/* 1 — один раз на старті прогнати набір запитів до модуля і надрукувати
   відповіді. Потрібно лише для з'ясування, що саме вміє прошивка модуля;
   у робочій прошивці 0 (економить ~4 с на старті).

   Результат зондування 18.11.2026 на цій платі: проста команда AT дає OK,
   а всі AT+BLE_* — ERROR, включно з AT+BLE_PUB_ADDR? (читання адреси, яке
   не потребує налаштування) і AT+BLE_SVC=1 (те, що робить приклад ST).
   Висновок: шар AT на модулі живий, підсистеми BLE немає. Треба прошити
   сам модуль STM32WB5MMG — див. firmware/BLE_SETUP.md. */
#define HAR_BLE_PROBE 0

/* Необов'язкові кроки ініціалізації: їхня відмова не валить канал, а лише
   піднімає біт у har_ble_soft_fail(). */
#define HAR_BLE_SOFT_NAME  (1u << 2)   /* AT+BLE_NAME */
#define HAR_BLE_SOFT_INIT  (1u << 3)   /* AT+BLE_INIT */
#define HAR_BLE_SOFT_RST   (1u << 4)   /* AT+BLE_RST */

/* Полярність WRLS_WKUP_B (PG6), яким вмикається модуль STM32WB5MMG.

   1 — підняти ногу в одиницю. Припущення за аналогією з WRLS_WKUP_W модуля
       Wi-Fi на цій же платі, де одиниця означає «увімкнено».
   0 — лишити ногу входом (високоімпедансним) рівно так, як це робить приклад
       ST BLE_AT_Client: він цю ногу не конфігурує взагалі.

   CubeMX за замовчуванням тримає PG6 виходом у нулі, і це не відповідає
   жодному з двох варіантів. Якщо har_ble_init() вертає 1 (модуль мовчить на
   просту команду AT) — спробуй інше значення цього макроса. */
#define HAR_BLE_DRIVE_WAKE_PIN 1

/* 0 is success; nonzero identifies the failing initialization step. */
uint8_t har_ble_init(void);

/* Send a newline-terminated prediction using <=18-byte BLE notifications.
   0 — успіх. Ненульове значення означає «цього разу не вийшло», а не
   «BLE більше не працює»: наступний виклик спробує знову. */
uint8_t har_ble_send(const char *data, uint16_t len);

/* 1, якщо ініціалізація пройшла і канал можна використовувати. */
uint8_t har_ble_ready(void);

/* Маска необов'язкових кроків, що не пройшли (HAR_BLE_SOFT_*). 0 — усі
   пройшли. Канал при цьому все одно робочий. */
uint8_t har_ble_soft_fail(void);

/* 1, якщо канал справді доставляє: піднявся, остання спроба дійшла і зараз
   не триває пауза після серії невдач. Для індикації на світлодіодах — без
   USB це єдиний спосіб побачити, чи йдуть дані в ефір. */
uint8_t har_ble_delivering(void);

#endif
